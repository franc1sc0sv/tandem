//! Automatic configuration on first start (T-082, T-087): if there is no `tandem.toml`,
//! the agent writes it on its own.
//!
//! - `machine` starts at `a`: the real side is decided by the keys when pairing
//!   (DECISIONS A1), not the operating system.
//! - **The desk starts empty**: without `[[screens]]`, each machine uses the screens the
//!   input engine reads and A goes to the left of B (DESIGN §7).
//! - Network, input and power with their default values and nothing invented: no fixed
//!   links, no Wake-on-LAN, no hub and without saying where the keyboard is (there is no way to
//!   guess a MAC, a VID:PID or the keyboard the person uses).
//!
//! A file that already exists is never touched, even if invalid.

use std::io;
use std::path::Path;

use tandem_core::Machine;

use crate::config::{AgentConfig, ConfigError, DEFAULT_PORT};
use crate::paths;

/// The side the configuration is generated with: `A` until pairing says otherwise.
/// `None` where Tandem does not really run (Linux): there it is not generated on its own.
pub fn initial_side() -> Option<Machine> {
    cfg!(any(target_os = "macos", windows)).then_some(Machine::A)
}

/// `tandem.toml` with side `machine`, commented and with an empty desk. It does not say where
/// the keyboard is either: without a hub or a user answer it is "not set". Always valid.
pub fn generate(machine: Machine) -> String {
    format!(
        "# Configuration generated by tandemd on first start (T-082, T-087).
# It can be edited: the agent does not generate it again while the file exists.
# This machine's side (`a` or `b`). Decided by the public key when pairing: the lower
# is `a`. The agent fixes it on its own.
machine = \"{side}\"
# The screen arrangement for the keyboard and mouse (DESIGN §7). Without `[[screens]]`, each
# machine uses the screens it reads itself, and A goes to the left of B. To
# declare it by hand (it holds for both machines, it syncs on its own):
# [[screens]]
# machine = \"b\"
# id = \"34\"
# x = 0
# y = 0
# width = 3440
# height = 1440
# scale = 1.0
#
# [arrangement]
# a_side = \"left\"
# align = \"center\"
#
# What is shared (arrangement, shortcuts, preferences, modules) is changed from the app of
# either machine; the agent writes it here.

[network]
# UDP port of the agent. If it cannot be opened, the agent tries others and announces the real one
# over mDNS: the other machine finds it all the same on the local network.
port = {DEFAULT_PORT}
# Direct links (USB4 and Ethernet) with the other machine's fixed address, if any:
# peers = [{{ kind = \"usb4\", addr = \"<ip>:<port>\" }}]

[input]
# Where the keyboard and mouse are is stated by the USB hub or setup (saved here as
# `keyboard = \"a\"` or `\"b\"`). Without that, the app says \"not set\".
# For the roles to change on their own when moving the hub, add [input.hub] with the VID:PID
# of the keyboard and the mouse (`keyboard` and `mouse`).

[power]
# Without any link to the other machine for this long, it is considered off.
peer_lost_after_secs = 15
# This machine is woken by Wake-on-LAN (it is announced to the other).
wakeable = true
# To power on the other machine from this one, add [power.wol] with the MAC of its network
# card (`mac`).
",
        side = machine.as_str()
    )
}

#[derive(Debug, thiserror::Error)]
pub enum AutoConfigError {
    #[error(transparent)]
    Config(#[from] ConfigError),
    #[error("could not write the generated configuration at {path}: {source}")]
    Write {
        path: String,
        #[source]
        source: io::Error,
    },
    #[error(
        "there is no configuration at {path} and on this system it is not generated on its own (only on macOS and Windows): pass it with --config"
    )]
    Unsupported { path: String },
}

/// The configuration at `path`, or the one generated if it does not exist.
#[derive(Debug)]
pub struct Loaded {
    pub config: AgentConfig,
    /// It was just generated.
    pub generated: bool,
}

/// Loads `path`; if it does not exist and `machine` is `Some`, generates it (see [`generate`]) and
/// writes it. It never replaces an existing file.
pub fn load_or_generate(path: &Path, machine: Option<Machine>) -> Result<Loaded, AutoConfigError> {
    match AgentConfig::load(path) {
        Ok(config) => {
            return Ok(Loaded {
                config,
                generated: false,
            });
        }
        Err(ConfigError::Read { source, .. }) if source.kind() == io::ErrorKind::NotFound => {}
        Err(e) => return Err(e.into()),
    }
    let shown = path.display().to_string();
    let Some(machine) = machine else {
        return Err(AutoConfigError::Unsupported { path: shown });
    };
    let text = generate(machine);
    let config = AgentConfig::from_toml(&text)?;
    let written = write_new(path, &text).map_err(|source| AutoConfigError::Write {
        path: shown.clone(),
        source,
    })?;
    if !written {
        // Another (the UI, the user) wrote it in between: that is the one that holds.
        return Ok(Loaded {
            config: AgentConfig::load(path)?,
            generated: false,
        });
    }
    tracing::info!("configuration generated at {shown}: side {machine} until pairing");
    Ok(Loaded {
        config,
        generated: true,
    })
}

/// `false` if it already existed (it is not touched).
fn write_new(path: &Path, text: &str) -> io::Result<bool> {
    if let Some(dir) = path.parent().filter(|d| !d.as_os_str().is_empty()) {
        paths::create_private_dir(dir)?;
    }
    // `create_new`: does not overwrite one that appears between the read and the write.
    match std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
    {
        Ok(mut file) => {
            io::Write::write_all(&mut file, text.as_bytes())?;
            Ok(true)
        }
        Err(e) if e.kind() == io::ErrorKind::AlreadyExists => Ok(false),
        Err(e) => Err(e),
    }
}

#[cfg(test)]
pub(crate) mod tests {
    use super::*;

    #[test]
    fn a_generated_config_has_an_empty_desk_and_no_keyboard() {
        for machine in [Machine::B, Machine::A] {
            let text = generate(machine);
            let cfg = AgentConfig::from_toml(&text).unwrap();
            assert_eq!(cfg.machine, machine);
            assert_eq!(
                cfg.desk,
                tandem_core::Config::default(),
                "the desk starts empty"
            );
            assert!(cfg.warnings().is_empty());
            assert_eq!(cfg.network.port, DEFAULT_PORT);
            assert!(cfg.network.peers.is_empty());
            assert_eq!(cfg.power.wol, None, "without an invented MAC");
            assert_eq!(cfg.input.hub, None, "without an invented VID:PID");
            assert!(
                !cfg.input.keyboard_defined(),
                "the keyboard is never assumed"
            );
            // Nor an example value that looks real.
            for fake in ["9c:6b", "046d", "10.77.", "monitors", "\"mac\"", "\"pc\""] {
                assert!(!text.contains(fake), "{fake} en\n{text}");
            }
        }
    }

    #[test]
    fn writes_once_and_never_replaces() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("Tandem").join("tandem.toml");
        let first = load_or_generate(&path, Some(Machine::B)).unwrap();
        assert!(first.generated);
        assert!(first.config.desk.screens.is_empty());
        assert_eq!(AgentConfig::load(&path).unwrap(), first.config);
        // The second time the file is read as is: even if someone adds screens.
        let mut text = std::fs::read_to_string(&path).unwrap();
        text.push_str(
            "\n[[screens]]\nmachine = \"b\"\nid = \"a\"\nx = 0\ny = 0\nwidth = 10\nheight = 10\n",
        );
        std::fs::write(&path, &text).unwrap();
        let again = load_or_generate(&path, Some(Machine::B)).unwrap();
        assert!(!again.generated);
        assert_eq!(again.config.desk.screens.len(), 1);
        assert_eq!(std::fs::read_to_string(&path).unwrap(), text);
    }

    #[test]
    fn an_invalid_file_is_an_error_not_a_new_config() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("tandem.toml");
        std::fs::write(&path, "machine = \"linux\"").unwrap();
        let err = load_or_generate(&path, Some(Machine::B)).unwrap_err();
        assert!(
            matches!(err, AutoConfigError::Config(ConfigError::Parse(_))),
            "{err}"
        );
        assert_eq!(
            std::fs::read_to_string(&path).unwrap(),
            "machine = \"linux\""
        );
    }

    #[test]
    fn without_a_known_os_it_asks_for_a_config() {
        let dir = tempfile::tempdir().unwrap();
        let path = dir.path().join("tandem.toml");
        let err = load_or_generate(&path, None).unwrap_err();
        assert!(matches!(err, AutoConfigError::Unsupported { .. }), "{err}");
        assert!(err.to_string().contains("--config"), "{err}");
        assert!(!path.exists());
    }
}
